"""Make Wow.exe (3.3.5a 12340) load LivingVoices.dll at startup -- the awesome_wotlk patch (GPL-3.0,
github.com/FrostAtom/awesome_wotlk, src/AwesomeWotlkPatch/Patch.h) with our DLL's name.

    python3 patch_wowexe.py <path to Wow.exe>         # writes Wow.exe.stock first; refuses anything but the stock exe
    python3 patch_wowexe.py <path to Wow.exe> --undo  # puts Wow.exe.stock back
    python3 patch_wowexe.py <stock Wow.exe> --header  # writes patch_bytes.h for the patcher exe (prints its PATCHED_SHA1)

The three patches:
  lua_ScanDllStart -> return 0 (the client's Lua-side DLL scan reports nothing)
  ScanDllStart     -> mark the scan finished, load our DLL via the client's own loader, then run StartAddress's
                      original first instructions and jump back
  StartAddress     -> jump to the code above
"""
import hashlib, shutil, struct, sys

STOCK_SHA1 = '178f78380affd260cb775d44397ba6b33ac05fdb'      # the realm's shipped Wow.exe, 3.3.5a (12340) enUS
PATCHED_SHA1 = 'bb9da1e1aec944cf8dafb880c113f325155a8884'    # the stock exe with this patch (LivingVoicesPatcher.cpp agrees)
DLL = b'LivingVoices.dll'
assert len(DLL) < 20                                            # the original name slot (AwesomeWotlkLib.dll\0) is 20 bytes

PATCHES = [
    (0x004DCCF0, 'B8 00000000 C3'),
    (0x004E5CB0, 'B8 01000000 A3 74B4B600 68 E05C4E00 E8 1C683800 83C404 55 8BEC E8 A110F2FF E9 045BF2FF'
                 + ' CC' * 12 + ' ' + (DLL + b'\0' * (20 - len(DLL))).hex()),
    (0x0040B7D0, 'E9 DBA40D00 909090'),
]

def file_offset(img, va):
    pe = struct.unpack_from('<I', img, 0x3C)[0]
    nsec = struct.unpack_from('<H', img, pe + 6)[0]; opt = struct.unpack_from('<H', img, pe + 20)[0]
    base = struct.unpack_from('<I', img, pe + 24 + 28)[0]
    for i in range(nsec):
        o = pe + 24 + opt + 40 * i
        vs, va_, rs, ra = struct.unpack_from('<IIII', img, o + 8)
        if va_ <= va - base < va_ + max(vs, rs): return ra + (va - base) - va_
    raise ValueError(hex(va))

def patch(img):
    for va, hexbytes in PATCHES:
        data = bytes.fromhex(hexbytes.replace(' ', ''))
        o = file_offset(img, va); img[o:o + len(data)] = data
    return img

def header(stock):
    """patch_bytes.h: every byte the patch changes (file offset, stock, patched). The 1.0.0 patch changed a subset
    of these offsets (only the DLL name differs), so writing the stock bytes back undoes either one."""
    img = patch(bytearray(stock))
    rows = [f'    {{0x{i:06X}, 0x{stock[i]:02X}, 0x{img[i]:02X}}}' for i in range(len(stock)) if stock[i] != img[i]]
    open('patch_bytes.h', 'w').write("// generated by patch_wowexe.py --header from the stock 3.3.5a Wow.exe (file offset, stock byte, patched byte)\n"
                                     "static const struct { unsigned off; unsigned char stock, patched; } PATCH[] = {\n"
                                     + ',\n'.join(rows) + '\n};\n')
    print(f'patch_bytes.h: {len(rows)} bytes; PATCHED_SHA1', hashlib.sha1(img).hexdigest())

def main():
    exe = sys.argv[1]
    if '--undo' in sys.argv:
        shutil.copy2(exe + '.stock', exe); print('restored', exe); return
    img = bytearray(open(exe, 'rb').read())
    h = hashlib.sha1(img).hexdigest()
    if '--header' in sys.argv:
        if h != STOCK_SHA1: sys.exit(f'--header needs the stock Wow.exe (sha1 {h})')
        header(img); return
    if h == PATCHED_SHA1: print(exe, 'is already patched for Living Voices'); return
    if h != STOCK_SHA1:
        sys.exit(f'refusing: {exe} is not the stock 3.3.5a client (sha1 {h}); already patched? use --undo first')
    shutil.copy2(exe, exe + '.stock')
    patch(img)
    open(exe, 'wb').write(img)
    print('patched', exe, '-> loads', DLL.decode(), '| backup:', exe + '.stock', '| sha1', hashlib.sha1(img).hexdigest())

if __name__ == '__main__':
    main()
